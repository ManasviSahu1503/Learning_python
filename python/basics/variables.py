# Variables in Python

name = "Varsha"
age = 21
height = 5.9
is_student = True

print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Student:", is_student)

# Multiple variables
x, y, z = 10, 20, 30

print(x, y, z)

# Changing a variable
age = 22
print("Updated age:", age)

# Variable naming
first_name = "Varsha"
college_name = "ABC College"

print(first_name)
print(college_name)